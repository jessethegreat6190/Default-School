CREATE TABLE IF NOT EXISTS payment_statement_imports (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  school_id BIGINT UNSIGNED NOT NULL,
  provider VARCHAR(50) NOT NULL,
  source_name VARCHAR(190) NULL,
  imported_by BIGINT UNSIGNED NULL,
  imported_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  total_rows INT NOT NULL DEFAULT 0,
  matched_rows INT NOT NULL DEFAULT 0,
  unmatched_rows INT NOT NULL DEFAULT 0,
  duplicate_rows INT NOT NULL DEFAULT 0,
  notes TEXT NULL,
  CONSTRAINT fk_psi_school FOREIGN KEY (school_id) REFERENCES schools(id),
  CONSTRAINT fk_psi_user FOREIGN KEY (imported_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS payment_statement_rows (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  import_id BIGINT UNSIGNED NOT NULL,
  school_id BIGINT UNSIGNED NOT NULL,
  provider VARCHAR(50) NOT NULL,
  provider_reference VARCHAR(100) NULL,
  payer_name VARCHAR(190) NULL,
  student_no VARCHAR(50) NULL,
  invoice_no VARCHAR(60) NULL,
  amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  currency VARCHAR(10) NOT NULL DEFAULT 'UGX',
  paid_at DATETIME NULL,
  raw_data JSON NULL,
  match_status VARCHAR(30) NOT NULL DEFAULT 'pending',
  matched_payment_id BIGINT UNSIGNED NULL,
  matched_invoice_id BIGINT UNSIGNED NULL,
  matched_student_id BIGINT UNSIGNED NULL,
  review_note TEXT NULL,
  created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_psr_import FOREIGN KEY (import_id) REFERENCES payment_statement_imports(id) ON DELETE CASCADE,
  CONSTRAINT fk_psr_school FOREIGN KEY (school_id) REFERENCES schools(id),
  CONSTRAINT fk_psr_payment FOREIGN KEY (matched_payment_id) REFERENCES payments(id),
  CONSTRAINT fk_psr_invoice FOREIGN KEY (matched_invoice_id) REFERENCES invoices(id),
  CONSTRAINT fk_psr_student FOREIGN KEY (matched_student_id) REFERENCES students(id),
  INDEX idx_psr_ref (provider_reference),
  INDEX idx_psr_status (match_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
