CREATE TABLE IF NOT EXISTS grading_scales (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  school_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(100) NOT NULL,
  is_default TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_gs_school FOREIGN KEY (school_id) REFERENCES schools(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS grade_rules (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  grading_scale_id BIGINT UNSIGNED NOT NULL,
  min_score DECIMAL(5,2) NOT NULL,
  max_score DECIMAL(5,2) NOT NULL,
  grade VARCHAR(20) NOT NULL,
  remark VARCHAR(100) NULL,
  division VARCHAR(50) NULL,
  sort_order INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_gr_scale FOREIGN KEY (grading_scale_id) REFERENCES grading_scales(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS assessments (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  school_id BIGINT UNSIGNED NOT NULL,
  term_id BIGINT UNSIGNED NULL,
  class_id BIGINT UNSIGNED NULL,
  name VARCHAR(150) NOT NULL,
  max_score DECIMAL(7,2) NOT NULL DEFAULT 100,
  weight DECIMAL(5,2) NOT NULL DEFAULT 100,
  assessment_date DATE NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ass_school FOREIGN KEY (school_id) REFERENCES schools(id),
  CONSTRAINT fk_ass_term FOREIGN KEY (term_id) REFERENCES terms(id),
  CONSTRAINT fk_ass_class FOREIGN KEY (class_id) REFERENCES classes(id),
  CONSTRAINT fk_ass_user FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS marks (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  school_id BIGINT UNSIGNED NOT NULL,
  assessment_id BIGINT UNSIGNED NOT NULL,
  student_id BIGINT UNSIGNED NOT NULL,
  subject_id BIGINT UNSIGNED NOT NULL,
  score DECIMAL(7,2) NULL,
  grade VARCHAR(20) NULL,
  remark VARCHAR(255) NULL,
  recorded_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_mark (assessment_id, student_id, subject_id),
  CONSTRAINT fk_marks_school FOREIGN KEY (school_id) REFERENCES schools(id),
  CONSTRAINT fk_marks_assessment FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,
  CONSTRAINT fk_marks_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
  CONSTRAINT fk_marks_subject FOREIGN KEY (subject_id) REFERENCES subjects(id),
  CONSTRAINT fk_marks_user FOREIGN KEY (recorded_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
